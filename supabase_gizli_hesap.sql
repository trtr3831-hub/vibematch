-- VibeMatch: gizli hesap ve takip istekleri
-- Supabase SQL editöründe bir kez çalıştırılır. Tekrar çalıştırmak güvenlidir.

-- 1) Takip istekleri (gizli hesaplar için bekleyen istek)
create table if not exists public.takip_istekleri (
  id bigint generated by default as identity primary key,
  istek_eden uuid not null default auth.uid() references auth.users(id) on delete cascade,
  hedef uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (istek_eden, hedef),
  check (istek_eden <> hedef)
);

alter table public.takip_istekleri enable row level security;

drop policy if exists "takip istegi okuma" on public.takip_istekleri;
create policy "takip istegi okuma" on public.takip_istekleri for select to authenticated
  using (istek_eden = auth.uid() or hedef = auth.uid());

drop policy if exists "takip istegi ekleme" on public.takip_istekleri;
create policy "takip istegi ekleme" on public.takip_istekleri for insert to authenticated
  with check (istek_eden = auth.uid());

drop policy if exists "takip istegi silme" on public.takip_istekleri;
create policy "takip istegi silme" on public.takip_istekleri for delete to authenticated
  using (istek_eden = auth.uid() or hedef = auth.uid());

-- 2) İsteği kabul: takipçi kaydını oluşturur ve isteği siler (yalnızca hedef kullanıcı)
create or replace function public.takip_istegi_kabul(istek_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  r record;
begin
  select * into r from public.takip_istekleri where id = istek_id and hedef = auth.uid();
  if not found then
    raise exception 'İstek bulunamadı veya size ait değil';
  end if;
  insert into public.takipler (takipci_id, takip_edilen_id)
  select r.istek_eden, r.hedef
  where not exists (
    select 1 from public.takipler t where t.takipci_id = r.istek_eden and t.takip_edilen_id = r.hedef
  );
  delete from public.takip_istekleri where id = istek_id;
end;
$$;

grant execute on function public.takip_istegi_kabul(bigint) to authenticated;

-- 3) Gizli hesaba doğrudan takip kaydı eklenemez; yalnızca istek yoluyla (kabul fonksiyonu hariç)
drop policy if exists "gizli hesaba dogrudan takip yok" on public.takipler;
create policy "gizli hesaba dogrudan takip yok" on public.takipler as restrictive for insert to authenticated
  with check (not exists (select 1 from public.profiles p where p.id = takip_edilen_id and p.gizlilik = 'takipci'));

-- 4) Gizli hesabın gönderileri ve hikayeleri: yalnızca sahibi ve onaylı takipçiler görür
drop policy if exists "gizli gonderi gorunurlugu" on public.gonderiler;
create policy "gizli gonderi gorunurlugu" on public.gonderiler as restrictive for select to authenticated
  using (
    user_id = auth.uid()
    or not exists (select 1 from public.profiles p where p.id = gonderiler.user_id and p.gizlilik = 'takipci')
    or exists (select 1 from public.takipler t where t.takipci_id = auth.uid() and t.takip_edilen_id = gonderiler.user_id)
  );

drop policy if exists "gizli hikaye gorunurlugu" on public.hikayeler;
create policy "gizli hikaye gorunurlugu" on public.hikayeler as restrictive for select to authenticated
  using (
    user_id = auth.uid()
    or not exists (select 1 from public.profiles p where p.id = hikayeler.user_id and p.gizlilik = 'takipci')
    or exists (select 1 from public.takipler t where t.takipci_id = auth.uid() and t.takip_edilen_id = hikayeler.user_id)
  );
