-- VibeMatch: gizli kasa (PIN özeti ve kasa öğeleri)
-- Supabase SQL editöründe bir kez çalıştırılır. Tekrar çalıştırmak güvenlidir.
-- Her iki tablo yalnızca sahibine açık: başka kullanıcılar satırları göremez.

create table if not exists public.kasa_ayar (
  user_id uuid primary key default auth.uid() references auth.users(id) on delete cascade,
  pin_hash text not null
);

create table if not exists public.kasa_ogeleri (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  foto text not null,
  created_at timestamptz not null default now()
);

alter table public.kasa_ayar enable row level security;
alter table public.kasa_ogeleri enable row level security;

drop policy if exists "kasa ayar okuma" on public.kasa_ayar;
create policy "kasa ayar okuma" on public.kasa_ayar for select to authenticated using (user_id = auth.uid());
drop policy if exists "kasa ayar ekleme" on public.kasa_ayar;
create policy "kasa ayar ekleme" on public.kasa_ayar for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "kasa ayar guncelleme" on public.kasa_ayar;
create policy "kasa ayar guncelleme" on public.kasa_ayar for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists "kasa ogesi okuma" on public.kasa_ogeleri;
create policy "kasa ogesi okuma" on public.kasa_ogeleri for select to authenticated using (user_id = auth.uid());
drop policy if exists "kasa ogesi ekleme" on public.kasa_ogeleri;
create policy "kasa ogesi ekleme" on public.kasa_ogeleri for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "kasa ogesi silme" on public.kasa_ogeleri;
create policy "kasa ogesi silme" on public.kasa_ogeleri for delete to authenticated using (user_id = auth.uid());
