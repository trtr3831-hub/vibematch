-- VibeMatch: Hikaye arşivi ve Öne çıkanlar (highlights)
-- Supabase SQL editöründe bir kez çalıştırılır. Tekrar çalıştırmak güvenlidir.

-- 1) Hikayeler: arşiv alanı (24 saat geçen hikayeler arşive düşer)
alter table public.hikayeler add column if not exists is_archived boolean not null default false;
create index if not exists hikayeler_kullanici_tarih on public.hikayeler (user_id, created_at desc);

-- 2) Highlight klasörleri
create table if not exists public.highlights (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  ad text not null check (char_length(ad) between 1 and 30),
  created_at timestamptz not null default now()
);

-- 3) Klasör-hikaye ilişkisi
create table if not exists public.highlight_hikayeler (
  highlight_id bigint not null references public.highlights(id) on delete cascade,
  hikaye_id bigint not null references public.hikayeler(id) on delete cascade,
  eklendi timestamptz not null default now(),
  primary key (highlight_id, hikaye_id)
);

alter table public.highlights enable row level security;
alter table public.highlight_hikayeler enable row level security;

-- Highlight'lar herkese açık okunur (profilde görünür); yazma yalnızca sahibine
drop policy if exists "highlight okuma" on public.highlights;
create policy "highlight okuma" on public.highlights for select to authenticated using (true);

drop policy if exists "highlight ekleme" on public.highlights;
create policy "highlight ekleme" on public.highlights for insert to authenticated with check (user_id = auth.uid());

drop policy if exists "highlight guncelleme" on public.highlights;
create policy "highlight guncelleme" on public.highlights for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists "highlight silme" on public.highlights;
create policy "highlight silme" on public.highlights for delete to authenticated using (user_id = auth.uid());

drop policy if exists "highlight hikaye okuma" on public.highlight_hikayeler;
create policy "highlight hikaye okuma" on public.highlight_hikayeler for select to authenticated using (true);

-- Yalnızca kendi highlight'ına, kendi hikayesini ekleyebilir
drop policy if exists "highlight hikaye ekleme" on public.highlight_hikayeler;
create policy "highlight hikaye ekleme" on public.highlight_hikayeler for insert to authenticated
  with check (
    exists (select 1 from public.highlights h where h.id = highlight_id and h.user_id = auth.uid())
    and exists (select 1 from public.hikayeler s where s.id = hikaye_id and s.user_id = auth.uid())
  );

drop policy if exists "highlight hikaye silme" on public.highlight_hikayeler;
create policy "highlight hikaye silme" on public.highlight_hikayeler for delete to authenticated
  using (exists (select 1 from public.highlights h where h.id = highlight_id and h.user_id = auth.uid()));

-- 4) Süresi dolan hikayeleri arşive taşıyan uç (istemci giriş yapınca çağırır)
create or replace function public.hikaye_arsivle()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  n integer;
begin
  update public.hikayeler
     set is_archived = true
   where user_id = auth.uid()
     and is_archived = false
     and created_at < now() - interval '24 hours';
  get diagnostics n = row_count;
  return n;
end;
$$;

grant execute on function public.hikaye_arsivle() to authenticated;
