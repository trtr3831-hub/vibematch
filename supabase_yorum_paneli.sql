-- VibeMatch: yorum paneli (gönderi ve reels yorumları, yorum beğenisi, reels beğenisi)
-- Supabase SQL editöründe bir kez çalıştırılır. Tekrar çalıştırmak güvenlidir.

-- 1) Gönderi yorumu beğenileri
create table if not exists public.yorum_begeniler (
  yorum_id bigint not null references public.yorumlar(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (yorum_id, user_id)
);

-- 2) Reels beğenileri
create table if not exists public.reel_begeniler (
  reel_id bigint not null references public.reeller(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (reel_id, user_id)
);

-- 3) Reels yorumları (yanıt için ust_id)
create table if not exists public.reel_yorumlar (
  id bigint generated by default as identity primary key,
  reel_id bigint not null references public.reeller(id) on delete cascade,
  ust_id bigint references public.reel_yorumlar(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  yazar text not null default 'kullanici',
  metin text not null check (char_length(metin) between 1 and 150),
  created_at timestamptz not null default now()
);

-- 4) Reels yorumu beğenileri
create table if not exists public.reel_yorum_begeniler (
  yorum_id bigint not null references public.reel_yorumlar(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (yorum_id, user_id)
);

alter table public.yorum_begeniler enable row level security;
alter table public.reel_begeniler enable row level security;
alter table public.reel_yorumlar enable row level security;
alter table public.reel_yorum_begeniler enable row level security;

-- Okuma: giriş yapmış herkes. Yazma/silme: yalnızca kendi satırı.
drop policy if exists "yorum begeni okuma" on public.yorum_begeniler;
create policy "yorum begeni okuma" on public.yorum_begeniler for select to authenticated using (true);
drop policy if exists "yorum begeni ekleme" on public.yorum_begeniler;
create policy "yorum begeni ekleme" on public.yorum_begeniler for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "yorum begeni silme" on public.yorum_begeniler;
create policy "yorum begeni silme" on public.yorum_begeniler for delete to authenticated using (user_id = auth.uid());

drop policy if exists "reel begeni okuma" on public.reel_begeniler;
create policy "reel begeni okuma" on public.reel_begeniler for select to authenticated using (true);
drop policy if exists "reel begeni ekleme" on public.reel_begeniler;
create policy "reel begeni ekleme" on public.reel_begeniler for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "reel begeni silme" on public.reel_begeniler;
create policy "reel begeni silme" on public.reel_begeniler for delete to authenticated using (user_id = auth.uid());

drop policy if exists "reel yorum okuma" on public.reel_yorumlar;
create policy "reel yorum okuma" on public.reel_yorumlar for select to authenticated using (true);
drop policy if exists "reel yorum ekleme" on public.reel_yorumlar;
create policy "reel yorum ekleme" on public.reel_yorumlar for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "reel yorum silme" on public.reel_yorumlar;
create policy "reel yorum silme" on public.reel_yorumlar for delete to authenticated using (user_id = auth.uid());

drop policy if exists "reel yorum begeni okuma" on public.reel_yorum_begeniler;
create policy "reel yorum begeni okuma" on public.reel_yorum_begeniler for select to authenticated using (true);
drop policy if exists "reel yorum begeni ekleme" on public.reel_yorum_begeniler;
create policy "reel yorum begeni ekleme" on public.reel_yorum_begeniler for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "reel yorum begeni silme" on public.reel_yorum_begeniler;
create policy "reel yorum begeni silme" on public.reel_yorum_begeniler for delete to authenticated using (user_id = auth.uid());
